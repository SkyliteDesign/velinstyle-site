import { readFileSync, writeFileSync } from 'fs';

function bodyOf(path) {
  const html = readFileSync(path, 'utf8');
  const m = html.match(/<body[^>]*>([\s\S]*)<\/body>/i);
  return (m ? m[1] : html)
    .replace(/<!-- Generated by velinstyle scaffold[\s\S]*?-->\n?/g, '')
    .trim();
}

const hero = bodyOf('assets/data/hero-demo.html');
const saas = bodyOf('assets/data/saas-demo.html');

const presets = {
  version: '1.2.0',
  prompts: [
    {
      id: 'lawyer',
      label: 'Tax advisor landing',
      prompt: 'Steuerberater Landingpage mit Leistungen, FAQ und Kontaktformular',
      components: ['velin-form-summary', 'velin-accordion', 'css-button', 'css-card', 'css-input'],
      html: hero,
    },
    {
      id: 'saas',
      label: 'SaaS landing',
      prompt: 'SaaS landing page with pricing and FAQ',
      components: ['velin-accordion', 'css-button', 'css-card'],
      html: saas,
    },
  ],
};

writeFileSync(
  'assets/js/demo-presets.js',
  `window.VELIN_DEMO_PRESETS = ${JSON.stringify(presets)};\n`,
);
console.log('ok', presets.prompts.map((p) => `${p.id}:${p.html.length}`).join(' '));
